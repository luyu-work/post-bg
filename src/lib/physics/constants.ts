// пятна как в лавовой лампе: медленно плывут, упруго пружинят формой, мягко сливаются при касании и сами отрываются
// друг от друга, когда вырастают, новые заплывают из-за края экрана, ушедшие за него пропадают
// единицы длины это меньшая сторона сетки, время в секундах

export const REACH = 0.75 // доля радиуса, на которой пятна считаются касающимися
export const MAX_EXTENT = 0.95 // пятно шире этой доли меньшей стороны экрана само разрывается
export const MIN_RADIUS = 0.13 // меньше этого капля впитывается в то, чего касается

export const MERGE_DEPTH = 0.85 // во сколько раз ближе суммы радиусов центры должны сойтись, чтобы капли слились
export const REPEL = 0.05 // мягкое выталкивание касающихся капель, пока они не могут слиться
export const MAX_SPEED = 0.1
export const DRAG = 0.1 // трение, 1/с, гасит толчки, а крейсерская скорость его перекрывает
export const HEADING_DRIFT = 0.5 // как быстро курс случайно уходит в сторону, рад/с, капли плывут по плавной дуге, а не по прямой

// деление как у клетки: большая капля вытягивается в перемычку и делится на две почти равные части,
// пока они расходятся, между ними тянется нить
export const PINCH_RADIUS = 0.5
export const PINCH_RATE = 0.06 // делений в секунду на подходящую каплю
export const PINCH_PUSH = 0.02 // скорость, с которой части расходятся
export const THREAD_BREAK = 1.3 // во сколько раз суммы радиусов должны разойтись части, чтобы нить оборвалась и они стали обычными каплями

// форма как пружина: после слияния или деления капля пульсирует, как желе, и успокаивается
export const SPRING = 18
export const DAMPING = 1.4
export const COLLIDE_SQUASH = 0.5 // на сколько касание сплющивает форму при полном нажиме, форма пружинит к этому значению
export const COLLIDE_MAX = 0.3 // глубже этого касание не добавляет сплющивания, чтобы пятна на старте не вытягивало
export const STRETCH_MIN = -0.25
export const STRETCH_MAX = 0.3

// появление новых пятен из-за края экрана
export const SPAWN_EVERY = [3, 8] as const // секунд между появлениями
export const SPAWN_URGENT = [0.8, 1.8] as const // секунд, если пятен меньше заданного числа
export const SPAWN_RADIUS = [0.3, 0.6] as const
export const SPAWN_SPEED = [0.035, 0.06] as const
export const EDGE_MARGIN = 1.3 // насколько радиусов от края пятно считается ушедшим за экран
export const START_SPEED = 0.02

// куда плывут новые пятна: с этой вероятностью цель случайная точка в центральной половине экрана, иначе просто внутрь
export const SEEK_CHANCE = 0.6
export const SEEK_AREA = 0.5 // доля ширины и высоты экрана вокруг центра
export const STEER = 0.6 // как быстро скорость подстраивается под путь к цели, 1/с
export const ARRIVED = 0.12 // на таком расстоянии от цели пятно перестает ее искать и плывет дальше по инерции

export const SUBSTEP = 1 / 60
